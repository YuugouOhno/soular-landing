// 重要事項説明書 第1項の本文を契約プランから組み立てる。
// 既定の 3年契約プラン (初期費用0円・月額未確定) では、従来ベタ書きだった文面と
// 1 文字も変わらない出力になるよう組んである (document_hash と配置済み PDF の互換維持)。
function buildImportantItem1(plan: ContractPlan, fees?: DealFees | null): LegalSection {
  const terms = effectivePlanTerms(plan, fees);

  // 初期費用が未確定のプランでは、この修飾句ごと落とす。
  const initialFeeClause =
    terms.initialFeeYen === null
      ? ""
      : terms.initialFeeYen === 0
        ? "導入時の初期費用を0円（無料）とした"
        : `導入時の初期費用を${formatYen(terms.initialFeeYen)}とした`;

  const body = [
    `医療機関における組織風土の改善やスタッフの定着には、一朝一夕ではなく、一定の期間を要します。そのため弊社では、長期的な視点で本気で組織改善に取り組まれる院長先生を応援すべく、${initialFeeClause}「${terms.label}」をご用意しております。`,
    `本プランは${terms.years}年間（${terms.months}ヶ月）の継続利用を条件とした特別契約であるため、万が一、期間満了前に中途解約をされる場合は、誠に恐縮ながら「残余期間分の月額利用料相当額」を違約金（損害賠償額の予定）として、一括してご精算いただきますようお願い申し上げます。`,
  ];

  // 料金は確定したプランでのみ明記する (未確定のうちに仮の数値を出さない)。
  // 金額を入れた時点で本文が変わるため、POLICY_VERSIONS.important の更新と
  // PDF 再生成が必要になる (plan.ts の注意書きを参照)。
  if (terms.monthlyFeeYen !== null) {
    const initialFeeText =
      terms.initialFeeYen === null
        ? ""
        : `導入時の初期費用は${terms.initialFeeYen === 0 ? "0円（無料）" : formatYen(terms.initialFeeYen)}、`;
    body.push(
      `【ご利用料金】${initialFeeText}月額利用料は${formatYen(terms.monthlyFeeYen)}（税別）です。${terms.months}ヶ月の継続利用を前提とした料金設定であり、上記の中途解約時の精算はこの月額利用料を基準に算定いたします。`,
    );
  }

  return { heading: `第1項 【${terms.label}の適用条件と中途解約について】`, body };
}

